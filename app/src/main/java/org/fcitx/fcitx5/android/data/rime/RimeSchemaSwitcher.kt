package org.fcitx.fcitx5.android.data.rime

import org.fcitx.fcitx5.android.core.Action
import org.fcitx.fcitx5.android.core.FcitxAPI
import timber.log.Timber
import java.io.File

/**
 * 在 Rime 用户目录写 `default.custom.yaml`，在朙月简拼 / 雾凇之间切换，
 * 并强制 Shift 不进 Rime ASCII（留给巨硬选字 / 中英切换）。
 */
object RimeSchemaSwitcher {

    const val LUNA_SIMP = "luna_pinyin_simp"
    const val RIME_ICE = "rime_ice"
    const val RIME_FROST = "rime_frost"
    const val RIME_MINT = "rime_mint"

    fun apply(schemaId: String) {
        val dir = RimePaths.userDir()
        dir.mkdirs()
        val custom = File(dir, "default.custom.yaml")
        custom.writeText(customYaml(schemaId), Charsets.UTF_8)
        Timber.i("rime schema switch -> %s (%s)", schemaId, custom.absolutePath)
    }

    fun customYaml(schemaId: String): String = """
        # encoding: utf-8
        # Generated by TapFeet — do not hand-edit; toggled with 中文拼音引擎.
        patch:
          schema_list:
            - schema: $schemaId
          switcher/hotkeys: []
          menu/page_size: 5
          ascii_composer/switch_key:
            Shift_L: noop
            Shift_R: noop
            Control_L: noop
            Control_R: noop
            Caps_Lock: clear
            Eisu_toggle: clear
    """.trimIndent() + "\n"

    /**
     * 触发 fcitx5-rime 的 Deploy；找不到动作时返回 false，由调用方决定是否重启 Fcitx。
     */
    suspend fun deploy(api: FcitxAPI): Boolean {
        val deploy = findDeploy(api.statusArea()) ?: return false
        api.activateAction(deploy.id)
        return true
    }

    private fun findDeploy(actions: Array<Action>): Action? {
        for (a in actions) {
            if (a.name == "fcitx-rime-deploy" || a.icon == "fcitx_rime_deploy") return a
            if (a.shortText.contains("Deploy", ignoreCase = true) ||
                a.shortText.contains("部署")
            ) {
                return a
            }
            a.menu?.let { findDeploy(it)?.let { hit -> return hit } }
        }
        return null
    }
}
